CREATE ROLE workpilot_owner LOGIN PASSWORD 'workpilot_owner' NOSUPERUSER NOCREATEDB NOCREATEROLE;
CREATE ROLE workpilot_app LOGIN PASSWORD 'workpilot_app' NOSUPERUSER NOCREATEDB NOCREATEROLE;
CREATE DATABASE workpilot OWNER workpilot_owner;

\connect workpilot

CREATE EXTENSION IF NOT EXISTS vector;
GRANT CONNECT ON DATABASE workpilot TO workpilot_app;
GRANT USAGE ON SCHEMA public TO workpilot_app;

ALTER DEFAULT PRIVILEGES FOR ROLE workpilot_owner IN SCHEMA public
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO workpilot_app;
ALTER DEFAULT PRIVILEGES FOR ROLE workpilot_owner IN SCHEMA public
  GRANT USAGE, SELECT ON SEQUENCES TO workpilot_app;

